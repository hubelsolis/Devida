CREATE VIEW VPADRON (IDPADRON, IDADENDA, IDCASERIO, CODIGO, OZ, AMBITO, DEPARTAMENTO, PROVINCIA, DISTRITO, CASERIO, APPATERNO, APMATERNO, NOMBRE, 
DNI, SEXO, ETNIA, LENGUA, TELEFONO, FECNAC, EDAD, 
CONY_APPATERNO, CONY_APMATERNO, CONY_NOMBRE, CONY_DNI, CONY_SEXO, CONY_ETNIA, CONY_LENGUA, CONY_TELEFONO, CONY_FECNAC, CONY_EDAD, ANIO_INCORPORACION, 
INST_CACAO, CREC_CACAO, PROD_CACAO, TOTAL_CACAO, 
INST_CAFE, CREC_CAFE, PROD_CAFE, TOTAL_CAFE,
INST_PLA,CREC_PLA,PROD_PLA,TOTAL_PLA, 
ACT_ACUICOLA, ACT_APICOLA, PCAC_SANIDAD, PCAF_SANIDAD, 
COORX_CACAO, COORY_CACAO, ALTITUD_CACAO, 
COORX_CAFE, COORY_CAFE, ALTITUD_CAFE, 
COORX_PLA, COORY_PLA, ALTITUD_PLA,
COORX_SPCC, COORY_SPCC, ALTITUD_SPCC, COORX_SPCF, COORY_SPCF, ALTITUD_SPCF, 
COORX_ACUI, COORY_ACUI, ALTITUD_ACUI, COORX_API, COORY_API, ALTITUD_API, 
OBSERVACIONES, JUSTIFICACION)
AS   
SELECT a.IDPADRON, a.IDADENDA, a.IDCASERIO, a.CODIGO, a.OZ, a.AMBITO, a.DEPARTAMENTO, a.PROVINCIA, a.DISTRITO, a.CASERIO, 
a.ApPATERNO, a.ApMATERNO, a.NOMBRE, a.DNI, a.SEXO, a.ETNIA, a.LENGUA, a.TELEFONO, 
(select p.fecnac from persona p where p.DNI=a.dni) fecnac, 
(select datediff (year, p.FECNAC, current_date) from persona p where p.DNI=a.dni) edad, 
a.CONY_ApPATERNO,a.CONY_ApMATERNO, a.CONY_NOMBRE, a.CONY_DNI, a.CONY_SEXO, a.CONY_ETNIA, a.CONY_LENGUA,
(select p.TELEFONO from persona p where p.DNI=a.CONY_dni) CONY_TELEFONO,
(select p.FECNAC from persona p where p.DNI=a.CONY_dni) CONY_fecnac, 
(select datediff (year, p.FECNAC, current_date) from persona p where p.DNI=a.CONY_dni) CONY_edad, 
a.ANIO_INCORPORACION, 

(select p.HAS from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='CACAO' and p.IDETAPA='HAS INST') INST_CACAO, 
(select p.HAS from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='CACAO' and p.IDETAPA='HAS CREC') CREC_CACAO, 
(select p.HAS from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='CACAO' and p.IDETAPA='HAS PROD') PROD_CACAO, 
(select SUM(p.HAS) from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='CACAO') TOTAL_CACAO, 

(select p.HAS from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='CAFE' and p.IDETAPA='HAS INST') INST_CAFE,   
(select p.HAS from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='CAFE' and p.IDETAPA='HAS CREC') CREC_CAFE,   
(select p.HAS from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='CAFE' and p.IDETAPA='HAS PROD') PROD_CAFE,   
(select SUM(p.HAS) from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='CAFE') TOTAL_CAFE,  

(select p.HAS from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='PLA' and p.IDETAPA='HAS INST') INST_PLA,   
(select p.HAS from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='PLA' and p.IDETAPA='HAS CREC') CREC_PLA,   
(select p.HAS from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='PLA' and p.IDETAPA='HAS PROD') PROD_PLA,   
(select SUM(p.HAS) from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='PLA') TOTAL_PLATANO, 

(select p.HAS from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='ACUI'    ) ACT_ACUICOLA, 
(select p.HAS from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='API'     ) ACT_APICOLA, 
(select p.HAS from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='S.CACAO' ) PCAC_SANIDAD, 
(select p.HAS from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='S.CAFE'  ) PCAF_SANIDAD, 

(select first 1 p.COORX   from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='CACAO') COORX_CACAO, 
(select first 1 p.COORY   from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='CACAO') COORY_CACAO, 
(select first 1 p.ALTITUD from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='CACAO') ALTITUD_CACAO, 

(select first 1 p.COORX   from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='CAFE') COORX_CAFE, 
(select first 1 p.COORY   from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='CAFE') COORY_CAFE, 
(select first 1 p.ALTITUD from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='CAFE') ALTITUD_CAFE, 

(select first 1 p.COORX   from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='PLA') COORX_PLA, 
(select first 1 p.COORY   from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='PLA') COORY_PLA, 
(select first 1 p.ALTITUD from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='PLA') ALTITUD_PLA, 

(select first 1 p.COORX   from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='S.CACAO') COORX_SPCC, 
(select first 1 p.COORY   from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='S.CACAO') COORY_SPCC, 
(select first 1 p.ALTITUD from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='S.CACAO') ALTITUD_SPCC, 

(select first 1 p.COORX   from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='S.CAFE') COORX_SPCF, 
(select first 1 p.COORY   from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='S.CAFE') COORY_SPCF, 
(select first 1 p.ALTITUD from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='S.CAFE') ALTITUD_SPCF, 

(select first 1 p.COORX   from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='ACUI') COORX_ACUI, 
(select first 1 p.COORY   from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='ACUI') COORY_ACUI, 
(select first 1 p.ALTITUD from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='ACUI') ALTITUD_ACUI, 

(select first 1 p.COORX   from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='API') COORX_API, 
(select first 1 p.COORY   from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='API') COORY_API, 
(select first 1 p.ALTITUD from PADRONACTIVIDAD p where p.IDPADRON=a.IDPADRON and p.IDACTIVIDAD='API') ALTITUD_API, 
a.OBSERVACIONES, a.JUSTIFICACION
FROM PADRON a;

GRANT DELETE, INSERT, REFERENCES, SELECT, UPDATE
 ON VPADRON TO  SYSDBA WITH GRANT OPTION;
