CREATE PROCEDURE ANEXO8_IDADENDA (
    -- DATOS DE INGRESO
    DADENDA  Varchar(18))
RETURNS (
    -- CAMPOS DE SALIDA
    CAPPATERNO VARCHAR(64),
    CAPMATERNO VARCHAR(64),
    CNOMBRE VARCHAR(64),
    CDNI VARCHAR(10),
    CEDAD BIGINT,
    CTELEFONO VARCHAR(16),
    CSEXO VARCHAR(2),
    CTIPODOC VARCHAR(10),
    CCONY_APPATERNO VARCHAR(64),
    CCONY_APMATERNO VARCHAR(64),
    CCONY_NOMBRE VARCHAR(64),
    CCONY_DNI VARCHAR(10),
    CCONY_EDAD BIGINT,
    CCONY_TELEFONO VARCHAR(16),
    CCONY_SEXO VARCHAR(2),
    CCONY_TIPODOC VARCHAR(10),
    CANIO_INCORPORACION VARCHAR(16),
    CAMPOA1 VARCHAR(16),
    CAMPOA2 VARCHAR(16),
    CAMPOA3 Numeric(18,2),
    CAMPOA4 VARCHAR(16),
    CAMPOA5 VARCHAR(16),
    CAMPOB1 VARCHAR(16),
    CAMPOB2 VARCHAR(16),
    CAMPOB3 Numeric(18,2),
    CAMPOB4 VARCHAR(16),
    CAMPOB5 VARCHAR(16),
    CAMPOC1 VARCHAR(16),
    CAMPOC2 VARCHAR(16),
    CAMPOC3 Numeric(18,2),
    CAMPOC4 VARCHAR(16),
    CAMPOC5 VARCHAR(16)        
 )
AS
DECLARE VARIABLE pINST_CACAO NUMERIC(18,2);
DECLARE VARIABLE pANIO_INST_INST_CACAO VARCHAR(16);
DECLARE VARIABLE pANIO_ADOP_INST_CACAO VARCHAR(16);
 	
DECLARE VARIABLE pCREC_CACAO NUMERIC(18,2);
DECLARE VARIABLE pANIO_INST_CREC_CACAO VARCHAR(16);
DECLARE VARIABLE pANIO_ADOP_CREC_CACAO VARCHAR(16);
 	
DECLARE VARIABLE pPROD_CACAO NUMERIC(18,2);
DECLARE VARIABLE pANIO_INST_PROD_CACAO VARCHAR(16);
DECLARE VARIABLE pANIO_ADOP_PROD_CACAO VARCHAR(16);
 	
DECLARE VARIABLE pINST_CAFE NUMERIC(18,2);
DECLARE VARIABLE pANIO_INST_INST_CAFE VARCHAR(16);
DECLARE VARIABLE pANIO_ADOP_INST_CAFE VARCHAR(16);
 	
DECLARE VARIABLE pCREC_CAFE NUMERIC(18,2);
DECLARE VARIABLE pANIO_INST_CREC_CAFE VARCHAR(16);
DECLARE VARIABLE pANIO_ADOP_CREC_CAFE VARCHAR(16);
 	
DECLARE VARIABLE pPROD_CAFE NUMERIC(18,2);
DECLARE VARIABLE pANIO_INST_PROD_CAFE VARCHAR(16);
DECLARE VARIABLE pANIO_ADOP_PROD_CAFE VARCHAR(16);
 	
DECLARE VARIABLE pINST_PLA NUMERIC(18,2);
DECLARE VARIABLE pANIO_INST_INST_PLA VARCHAR(16);
DECLARE VARIABLE pANIO_ADOP_INST_PLA VARCHAR(16);
 	
DECLARE VARIABLE pCREC_PLA NUMERIC(18,2);
DECLARE VARIABLE pANIO_INST_CREC_PLA VARCHAR(16);
DECLARE VARIABLE pANIO_ADOP_CREC_PLA VARCHAR(16);
 	
DECLARE VARIABLE pPROD_PLA NUMERIC(18,2);
DECLARE VARIABLE pANIO_INST_PROD_PLA VARCHAR(16);
DECLARE VARIABLE pANIO_ADOP_PROD_PLA VARCHAR(16);
 	
DECLARE VARIABLE pPCAC_SANIDAD  NUMERIC(18,2);
DECLARE VARIABLE pANIO_INST_SCACAO  VARCHAR(16);
DECLARE VARIABLE pANIO_ADOP_SCACAO VARCHAR(16);
 	
DECLARE VARIABLE pPCAF_SANIDAD  NUMERIC(18,2);
DECLARE VARIABLE pANIO_INST_SCAFE  VARCHAR(16);
DECLARE VARIABLE pANIO_ADOP_SCAFE  VARCHAR(16);
 	
DECLARE VARIABLE pACT_ACUICOLA  NUMERIC(18,2);
DECLARE VARIABLE pANIO_INST_ACUI  VARCHAR(16);
DECLARE VARIABLE pANIO_ADOP_ACUI VARCHAR(16);
 	
DECLARE VARIABLE pACT_APICOLA  NUMERIC(18,2);
DECLARE VARIABLE pANIO_INST_API  VARCHAR(16);
DECLARE VARIABLE pANIO_ADOP_API VARCHAR(16);

BEGIN 
   -- INICIA EL BUCLE
   FOR           
        ---------------------------------------------------------------------------------------------
        SELECT 
        p.APPATERNO,p.APMATERNO,p.NOMBRE,p.DNI,p.edad,p.telefono,p.sexo,case coalesce(p.DNI,'') when '' then ''else 'DNI' end TIPODOC,
        p.CONY_APPATERNO,p.CONY_APMATERNO,p.CONY_NOMBRE,p.CONY_DNI,p.CONY_edad,p.CONY_telefono,p.CONY_sexo,
        case coalesce(p.CONY_DNI,'') when '' then ''else 'DNI' end CONY_TIPODOC,
        p.ANIO_INCORPORACION,

        -- PARA CACAO

        --'CACAO' ACT_CACAO_INST,
        --'INST'  ACT_CACAO_INST_ETAPA,
        p.INST_CACAO,
        p.ANIO_INST_INST_CACAO,
        p.ANIO_ADOP_INST_CACAO,

        --'CACAO' ACT_CACAO_CREC,
        --'CREC'  ACT_CACAO_CREC_ETAPA,
        p.CREC_CACAO,
        p.ANIO_INST_CREC_CACAO,
        p.ANIO_ADOP_CREC_CACAO,

        --'CACAO' ACT_CACAO_PROD,
        --'PROD' ACT_CACAO_PROD_ETAPA,
        p.PROD_CACAO,
        p.ANIO_INST_PROD_CACAO,
        p.ANIO_ADOP_PROD_CACAO,

        -- PARA CAFE

        --'CAFE' ACT_CAFE_INST,
        --'INST'  ACT_CAFE_INST_ETAPA,
        p.INST_CAFE,
        p.ANIO_INST_INST_CAFE,
        p.ANIO_ADOP_INST_CAFE,

        --'CAFE' ACT_CAFE_CREC,
        --'CREC'  ACT_CAFE_CREC_ETAPA,
        p.CREC_CAFE,
        p.ANIO_INST_CREC_CAFE,
        p.ANIO_ADOP_CREC_CAFE,

        --'CAFE' ACT_CAFE_PROD,
        --'PROD' ACT_CAFE_PROD_ETAPA,
        p.PROD_CAFE,
        p.ANIO_INST_PROD_CAFE,
        p.ANIO_ADOP_PROD_CAFE,

        -- PARA PLATANO
        --'PLA' ACT_PLA_INST,
        --'INST'  ACT_PLA_INST_ETAPA,
        p.INST_PLA,
        p.ANIO_INST_INST_PLA,
        p.ANIO_ADOP_INST_PLA,

        --'PLA' ACT_PLA_CREC,
        --'CREC'  ACT_PLA_CREC_ETAPA,
        p.CREC_PLA,
        p.ANIO_INST_CREC_PLA,
        p.ANIO_ADOP_CREC_PLA,

        --'PLA' ACT_PLA_PROD,
        --'PROD' ACT_PLA_PROD_ETAPA,
        p.PROD_PLA,
        p.ANIO_INST_PROD_PLA,
        p.ANIO_ADOP_PROD_PLA,

        -- PARA SANIDA CACAO
        --'S.CACAO' ACT_SCACAO, 
        --'PROD' ACT_SCACAO_ETAPA, 
        p.PCAC_SANIDAD, 
        p.ANIO_INST_SCACAO, 
        p.ANIO_ADOP_SCACAO,

        -- PARA SANIDA CAFE
        --'S.CAFE' ACT_SCAFE, 
        --'PROD' ACT_SCAFE_ETAPA, 
        p.PCAF_SANIDAD, 
        p.ANIO_INST_SCAFE, 
        p.ANIO_ADOP_SCAFE, 

        -- PARA ACUI
        --'ACUI' ACT_ACUI, 
        --'PROD' ACT_ACUI_ETAPA, 
        p.ACT_ACUICOLA, 
        p.ANIO_INST_ACUI, 
        p.ANIO_ADOP_ACUI,

        -- PARA API
        --'API' ACT_API, 
        --'PROD' ACT_API_ETAPA, 
        p.ACT_APICOLA, 
        p.ANIO_INST_API, 
        p.ANIO_ADOP_API

        FROM vPadron p 
        Where p.Idadenda=:DADENDA
        -- and p.idcaserio='1006050003' 
        order by 1,2,3
           
       INTO  
        :CAPPATERNO ,
        :CAPMATERNO ,
        :CNOMBRE ,
        :CDNI ,
        :CEDAD ,
        :CTELEFONO ,
        :CSEXO ,
        :CTIPODOC ,
        :CCONY_APPATERNO ,
        :CCONY_APMATERNO ,
        :CCONY_NOMBRE ,
        :CCONY_DNI ,
        :CCONY_EDAD ,
        :CCONY_TELEFONO ,
        :CCONY_SEXO ,
        :CCONY_TIPODOC ,
        :CANIO_INCORPORACION,
        
        : pINST_CACAO ,
        : pANIO_INST_INST_CACAO ,
        : pANIO_ADOP_INST_CACAO ,
         
        : pCREC_CACAO ,
        : pANIO_INST_CREC_CACAO ,
        : pANIO_ADOP_CREC_CACAO ,
         
        : pPROD_CACAO ,
        : pANIO_INST_PROD_CACAO ,
        : pANIO_ADOP_PROD_CACAO ,
         
        : pINST_CAFE ,
        : pANIO_INST_INST_CAFE ,
        : pANIO_ADOP_INST_CAFE ,
         
        : pCREC_CAFE ,
        : pANIO_INST_CREC_CAFE ,
        : pANIO_ADOP_CREC_CAFE ,
         
        : pPROD_CAFE ,
        : pANIO_INST_PROD_CAFE ,
        : pANIO_ADOP_PROD_CAFE ,
         
        : pINST_PLA ,
        : pANIO_INST_INST_PLA ,
        : pANIO_ADOP_INST_PLA ,
         
        : pCREC_PLA ,
        : pANIO_INST_CREC_PLA ,
        : pANIO_ADOP_CREC_PLA ,
         
        : pPROD_PLA ,
        : pANIO_INST_PROD_PLA ,
        : pANIO_ADOP_PROD_PLA ,
         
        : pPCAC_SANIDAD  ,
        : pANIO_INST_SCACAO  ,
        : pANIO_ADOP_SCACAO ,
         
        : pPCAF_SANIDAD  ,
        : pANIO_INST_SCAFE  ,
        : pANIO_ADOP_SCAFE  ,
         
        : pACT_ACUICOLA  ,
        : pANIO_INST_ACUI  ,
        : pANIO_ADOP_ACUI ,
         
        : pACT_APICOLA  ,
        : pANIO_INST_API  ,
        : pANIO_ADOP_API        
             
      DO   
   BEGIN   
   
    
    suspend;  
   END   
END^
SET TERM ; ^


